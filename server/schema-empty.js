// Writes docs/create-empty-db.sql: schema + migrations + reference data (permissions, roles, settings), no users.
// Built from a throwaway DB through the app's own db.js + bootstrap(), so it always matches what the server creates.
// Usage: npm run schema:empty   — re-run after any schema.sql / addColumn() / permission change.
import './env.js';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const tmp = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'itam-schema-')), 'empty.db');
process.env.DB_PATH = tmp;

const { db, ROOT } = await import('./db.js');
const { bootstrap } = await import('./bootstrap.js');
bootstrap();

const OUT = path.join(ROOT, 'docs', 'create-empty-db.sql');
const REF_DATA = ['permissions', 'roles', 'role_permissions', 'settings'];
const lit = (v) => v === null ? 'NULL'
  : typeof v === 'number' || typeof v === 'bigint' ? String(v)
  : `'${String(v).replace(/'/g, "''")}'`;

const objs = db.prepare(
  "SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY name"
).all();
const of = (type) => objs.filter((o) => o.type === type);

const L = [
  '-- IT Store (ITAM) — create an empty database',
  '-- Generated by `npm run schema:empty` (server/schema-empty.js) from server/schema.sql + addColumn() migrations + bootstrap().',
  '-- Usage:  sqlite3 data/it_storage.db < docs/create-empty-db.sql   (target file must not exist yet)',
  '-- Contains no users: the server creates admin / Admin@1234 on first start (server/bootstrap.js).',
  '',
  'PRAGMA journal_mode = WAL;',
  'PRAGMA foreign_keys = OFF;',
  'BEGIN TRANSACTION;',
  '',
  '-- TABLES',
];
for (const t of of('table')) L.push('', `${t.sql};`);
L.push('', '-- INDEXES', '');
for (const i of of('index')) L.push(`${i.sql};`);
L.push('', '-- REFERENCE DATA (permissions, system roles, default settings)');
for (const t of REF_DATA) {
  L.push('');
  for (const r of db.prepare(`SELECT * FROM ${t} ORDER BY rowid`).all()) {
    const cols = Object.keys(r);
    L.push(`INSERT INTO ${t} (${cols.join(', ')}) VALUES (${cols.map((c) => lit(r[c])).join(', ')});`);
  }
}
L.push('', '-- TRIGGERS (append-only logs and history)', '');
for (const t of of('trigger')) L.push(`${t.sql};`, '');
L.push('COMMIT;', 'PRAGMA foreign_keys = ON;', '');

db.close();
fs.rmSync(path.dirname(tmp), { recursive: true, force: true });
fs.writeFileSync(OUT, L.join('\n'), 'utf8');
console.log(`Wrote ${path.relative(ROOT, OUT)} — ${of('table').length} tables, ${of('index').length} indexes, ${of('trigger').length} triggers`);
